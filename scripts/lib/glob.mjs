// Convierte un glob simple en una expresión regular anclada.
// Soporta: ** (cualquier cantidad de carpetas), * (nombre dentro de una carpeta), ? (un carácter).
export function globARegex(glob) {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*' && glob[i + 1] === '*') {
      if (glob[i + 2] === '/') {
        re += '(?:.*/)?';
        i += 2;
      } else {
        re += '.*';
        i += 1;
      }
    } else if (c === '*') {
      re += '[^/]*';
    } else if (c === '?') {
      re += '[^/]';
    } else {
      re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
    }
  }
  return new RegExp(`^${re}$`);
}

export function coincide(ruta, globs) {
  return globs.some((g) => globARegex(g).test(ruta));
}
